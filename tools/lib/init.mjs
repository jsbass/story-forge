// `forge new` scaffolding and `forge setup` (per-project dependency install).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync, spawnSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { writeText, writeJson, listFiles } from './util.mjs';
import { PLUGIN_ROOT, projectPaths } from './project.mjs';
import { newPipeline } from './state.mjs';
import { commitAll, isRepo, git } from './git.mjs';

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'game';

function forgeYaml({ title, ifid }) {
  return `# Twine Forge project configuration
title: ${JSON.stringify(title)}
ifid: ${ifid}
format:
  name: SugarCube
  version: null        # filled in by \`forge setup\` from vendor/sugarcube-2
start: null            # start passage (scene id); defaults to the first scene in design/branch-map.yaml
size: null             # short | medium | long - set in the interview
rating:
  target: null         # e.g. E, T, M - set in the interview
  avoid: []            # themes/content to keep out (checked by QA)
voice_over: false
distribution: [itch, single-html, web, desktop]
style_profile: null
gates:                 # stages that pause for your approval (all on by default)
  interview: true
  bible: true
  characters: true
  loops: true
  script: true
  build: true
  qa: true
  playtest: true
limits:
  qa_fix_retries: 3
  generations_per_asset: 4
runtime:
  history_max_states: 20
vars: {}               # extra story variables: name: initial value
`;
}

const GITIGNORE = `node_modules/
.forge/
build/
qa/playthroughs/
assets/raw/
`;

/** Create a new game project folder. Does not install anything (see setupProject). */
export function scaffoldProject(dir, { title }) {
  const root = path.resolve(dir);
  if (fs.existsSync(root) && fs.readdirSync(root).length) throw new Error(`Folder isn't empty: ${root}`);
  const ifid = crypto.randomUUID().toUpperCase();
  const p = projectPaths(root);
  fs.mkdirSync(root, { recursive: true });
  writeText(p.config, forgeYaml({ title, ifid }));
  writeText(path.join(root, '.gitignore'), GITIGNORE);
  writeJson(path.join(root, 'package.json'), {
    name: slug(title),
    private: true,
    description: `${title} - a Twine Forge game`,
    type: 'module',
    scripts: { forge: 'node .forge/forge.mjs' },
  });
  writeJson(p.pipeline, newPipeline());
  writeJson(p.deps, { artifacts: {} });
  writeJson(path.join(p.feedback, 'index.json'), { next: 1, items: [] });
  for (const d of [p.loopsDir, p.characters, p.script, path.join(p.src, 'custom'), path.join(p.qa, 'reports')]) {
    writeText(path.join(d, '.gitkeep'), '');
  }
  writeText(path.join(root, 'README.md'), `# ${title}\n\nA Twine Forge project. Run \`/forge:status\` in Claude Code to see where it stands.\n`);
  writeShim(root);
  writeLaunchJson(root);
  if (!isRepo(root)) git(root, ['init', '-q', '-b', 'main']);
  return root;
}

/** .forge/forge.mjs lets agents run `node .forge/forge.mjs <cmd>` from the project root. */
export function writeShim(root) {
  const target = pathToFileURL(path.join(PLUGIN_ROOT, 'tools', 'forge.mjs')).href;
  writeText(path.join(root, '.forge', 'forge.mjs'), `// Generated by forge setup - points at the installed Twine Forge plugin.\nimport ${JSON.stringify(target)};\n`);
}

function writeLaunchJson(root) {
  writeJson(path.join(root, '.claude', 'launch.json'), {
    version: '0.0.1',
    configurations: [{ name: 'playtest', runtimeExecutable: 'node', runtimeArgs: ['.forge/forge.mjs', 'playtest', '--port', '4173'], port: 4173 }],
  });
}

function run(cmd, args, cwd, log) {
  log(`$ ${cmd} ${args.join(' ')}`);
  const r = spawnSync(cmd, args, { cwd, stdio: 'inherit', shell: process.platform === 'win32' });
  if (r.status !== 0) throw new Error(`${cmd} ${args.join(' ')} failed (exit ${r.status})`);
}

/** Download the latest SugarCube 2 release (official GitHub repo) into vendor/. */
export async function fetchSugarCube(root, { version = null, log = console.log } = {}) {
  const api = version
    ? `https://api.github.com/repos/tmedwards/sugarcube-2/releases/tags/v${version}`
    : 'https://api.github.com/repos/tmedwards/sugarcube-2/releases/latest';
  const rel = await (await fetch(api, { headers: { 'User-Agent': 'twine-forge', Accept: 'application/vnd.github+json' } })).json();
  const asset = (rel.assets || []).find((a) => /for-twine-2\.1-local\.zip$/.test(a.name));
  if (!asset) throw new Error(`No 'for-twine-2.1-local.zip' asset in SugarCube release ${rel.tag_name || '?'}`);
  log(`Downloading ${asset.name} (${Math.round(asset.size / 1024)} KB) from github.com/tmedwards/sugarcube-2`);
  const buf = Buffer.from(await (await fetch(asset.browser_download_url, { headers: { 'User-Agent': 'twine-forge' } })).arrayBuffer());
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-sc-'));
  const zip = path.join(tmp, asset.name);
  fs.writeFileSync(zip, buf);
  const out = path.join(tmp, 'x');
  fs.mkdirSync(out);
  extractZip(zip, out);
  const formatJs = listFiles(out, (f) => path.basename(f) === 'format.js')[0];
  if (!formatJs) throw new Error('format.js not found in the SugarCube archive');
  const dest = projectPaths(root).formatJs;
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(formatJs, dest);
  const licence = listFiles(out, (f) => /LICENSE/i.test(path.basename(f)))[0];
  if (licence) fs.copyFileSync(licence, path.join(path.dirname(dest), 'LICENSE'));
  fs.rmSync(tmp, { recursive: true, force: true });
  return rel.tag_name.replace(/^v/, '');
}

function extractZip(zip, out) {
  const attempts = [
    ['tar', ['-xf', zip, '-C', out]],
    ['unzip', ['-q', '-o', zip, '-d', out]],
    ['powershell', ['-NoProfile', '-Command', `Expand-Archive -LiteralPath '${zip}' -DestinationPath '${out}' -Force`]],
  ];
  for (const [cmd, args] of attempts) {
    try { execFileSync(cmd, args, { stdio: 'ignore' }); if (fs.readdirSync(out).length) return; } catch { /* next */ }
  }
  throw new Error('Could not extract zip (tried tar, unzip, PowerShell)');
}

/**
 * Install per-project dependencies:
 *  - npm: yaml, playwright (dev)   - Playwright Chromium browser   - SugarCube 2 story format
 */
export async function setupProject(root, { skipBrowsers = false, sugarcube = null, log = console.log } = {}) {
  writeShim(root);
  run('npm', ['install', '--save-dev', '--no-audit', '--no-fund', 'yaml@^2', 'playwright@^1'], root, log);
  if (!skipBrowsers) run('npx', ['playwright', 'install', 'chromium'], root, log);
  let version;
  if (sugarcube) {
    const dest = projectPaths(root).formatJs;
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(sugarcube, dest);
    version = (/"version"\s*:\s*"([^"]+)"/.exec(fs.readFileSync(dest, 'utf8')) || [])[1] || 'unknown';
  } else {
    version = await fetchSugarCube(root, { log });
  }
  // Record the format version in forge.yaml without needing the yaml lib.
  const cfgFile = projectPaths(root).config;
  const cfg = fs.readFileSync(cfgFile, 'utf8').replace(/(\n\s+version:\s*)(null|"[^"]*"|[\w.]+)/, `$1${JSON.stringify(version)}`);
  fs.writeFileSync(cfgFile, cfg);
  log(`SugarCube ${version} installed to vendor/sugarcube-2/format.js`);
  return { sugarcube: version };
}

export function initialCommit(root) {
  return commitAll(root, 'forge: new project');
}
