// Builder: script/*.script.md + design + characters -> src/**/*.twee -> build/{dev,release}/index.html
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { readText, writeText, writeJson, listFiles, rel, rmrf, timestampId } from '../lib/util.mjs';
import { loadProject, PLUGIN_ROOT } from '../lib/project.mjs';
import { compileScript, validateScripts, toTwee } from '../script/compiler.mjs';
import { parseTwee, wrapCode } from './twee.mjs';
import { loadStoryFormat, compileHtml } from './html.mjs';
import { loadDeps, saveDeps, recordDeps } from '../lib/deps.mjs';
import { readYaml } from '../lib/yaml.mjs';

export class BuildError extends Error {
  constructor(errors) {
    super(`${errors.length} error(s):\n` + errors.map((e) => `  ${e.file}:${e.line}  ${e.message}`).join('\n'));
    this.errors = errors;
  }
}

const GENERATED = '/* GENERATED by Twine Forge - edits will be overwritten. Put hand-written code in src/custom/. */';
const GENERATED_TWEE = '/% GENERATED by Twine Forge - do not edit; edit script/*.script.md instead. %/';
const PALETTE = ['#e0a458', '#7fb7be', '#d36582', '#9bc995', '#b39ddb', '#f2c14e', '#81a4cd', '#e57a44'];

/** Load a loop module implementation from the plugin's modules/ folder. */
export async function loadModuleType(type) {
  const dir = path.join(PLUGIN_ROOT, 'modules', type);
  if (!fs.existsSync(path.join(dir, 'module.mjs'))) {
    const known = fs.readdirSync(path.join(PLUGIN_ROOT, 'modules')).join(', ');
    throw new Error(`Unknown loop module type '${type}'. Available: ${known}`);
  }
  const impl = await import(pathToFileURL(path.join(dir, 'module.mjs')).href);
  return { dir, impl };
}

/**
 * Approved media for the build. Reads assets/manifest.yaml directly (no dependency on the assets module).
 * @returns {{files: Object<string,string>, urls: Object<string,string>, referenced: string[], missing: string[]}}
 *   files: "kind:id" -> project-relative source; urls: "kind:id" -> URL relative to the built index.html
 */
export function collectMedia(root, results) {
  const manifest = readYaml(path.join(root, 'assets', 'manifest.yaml'), root) || { assets: [] };
  const files = {};
  const urls = {};
  for (const a of manifest.assets || []) {
    const f = a.approved?.file;
    if (!f || !fs.existsSync(path.join(root, f))) continue;
    const k = `${a.kind}:${a.id}`;
    files[k] = f;
    urls[k] = `media/${a.kind}/${path.basename(f)}`;
  }
  const referenced = [...new Set(results.flatMap((r) => r.refs.media)
    .filter((m) => !((m.kind === 'music' || m.kind === 'ambience') && m.args[0] === 'none'))
    .map((m) => `${m.kind}:${m.kind === 'portrait' ? `${m.args[0]}.${m.args[1] || 'neutral'}` : m.args[0]}`))].sort();
  return { files, urls, referenced, missing: referenced.filter((k) => !files[k]) };
}

/** The generated forge-data.js passage: runtime data (characters, modules, asset URLs, build info). */
export function forgeDataJs(ctx, mode) {
  const set = (k, v, indent = 2) => `setup.forge.${k} = ${JSON.stringify(v, null, indent)};`;
  return [
    GENERATED,
    'setup.forge = setup.forge || {};',
    set('characters', ctx.characters),
    set('modules', ctx.modules),
    set('invariants', ctx.invariants),
    set('endings', ctx.endings),
    set('assets', ctx.assets),
    set('assetsSmall', ctx.assetsSmall || {}),
    set('posters', ctx.posters || {}),
    set('mediaByPassage', ctx.mediaByPassage || {}, 0),
    set('build', { ...ctx.build, mode }, 0),
    '',
  ].join('\n');
}

/**
 * Re-render a built mode's HTML with different runtime data (e.g. optimized or inlined asset URLs).
 * Uses build/<mode>/story.twee and build/forge-data.json from the last build.
 */
export function renderBuild(root, { mode = 'release', mutate = (ctx) => ctx } = {}) {
  const project = loadProject(root);
  const b = project.paths.build;
  const info = JSON.parse(readText(path.join(b, 'build-info.json')));
  const ctx = mutate(structuredClone(JSON.parse(readText(path.join(b, 'forge-data.json')))));
  const passages = parseTwee(readText(path.join(b, mode, 'story.twee'))).map((p) => (p.name === 'forge-data.js' ? { ...p, text: forgeDataJs(ctx, mode) } : p));
  const format = loadStoryFormat(readText(project.paths.formatJs));
  return { html: compileHtml({ passages, format, title: info.title, ifid: project.config.ifid, start: info.start }), ctx, info };
}

/** Compile and validate all scripts. */
export function compileScripts(project) {
  const files = listFiles(project.paths.script, (f) => f.endsWith('.script.md'));
  const results = files.map((f) => compileScript(readText(f), rel(project.root, f)));
  const customNames = listFiles(path.join(project.paths.src, 'custom'), (f) => f.endsWith('.twee')).flatMap((f) => parseTwee(readText(f)).map((p) => p.name));
  const charIds = project.characters.map((c) => c.id);
  const errors = [
    ...results.flatMap((r) => r.errors),
    ...validateScripts(results, { characters: charIds.length ? charIds : null, extraPassages: customNames }),
  ];
  return { files, results, errors };
}

export function resolveStart(project, results) {
  const bm = project.branchMap || {};
  return (
    project.config.start ||
    bm.start ||
    bm.acts?.[0]?.scenes?.[0]?.id ||
    results.flatMap((r) => r.passages)[0]?.name ||
    null
  );
}

async function collectVariablesAndModules(project) {
  const vars = new Map(); // name -> {init, source}
  const invariants = [];
  const modules = {};
  const moduleFiles = [];
  const errors = [];
  const add = (name, init, source) => {
    const n = String(name).replace(/^\$/, '');
    if (!vars.has(n)) vars.set(n, { init, source });
  };

  for (const m of project.loops.modules || []) {
    if (!m.id || !m.type) { errors.push({ file: 'design/loops/loops.yaml', line: 0, message: `Loop module needs 'id' and 'type': ${JSON.stringify(m)}` }); continue; }
    const { dir, impl } = await loadModuleType(m.type);
    const problems = impl.validate ? impl.validate(m.params || {}) : [];
    for (const p of problems) errors.push({ file: 'design/loops/loops.yaml', line: 0, message: `module ${m.id}: ${p}` });
    if (problems.length) continue;
    const params = impl.normalize ? impl.normalize(m.params || {}) : m.params || {};
    modules[m.id] = { type: m.type, ...params };
    for (const v of impl.variables ? impl.variables(m.params || {}) : []) add(v.name, v.init, `module ${m.id}`);
    invariants.push(...(impl.invariants ? impl.invariants(m.params || {}) : []));
    moduleFiles.push({ id: m.id, dir });
  }
  for (const c of project.characters) {
    const rel = c.relationships?.player;
    if (rel?.affinity_var) add(rel.affinity_var, rel.affinity_init ?? 0, `character ${c.id}`);
  }
  for (const [k, v] of Object.entries(project.branchMap?.variables || {})) add(k, v, 'branch-map');
  for (const [k, v] of Object.entries(project.config.vars || {})) add(k, v, 'forge.yaml');
  return { vars, invariants, modules, moduleFiles, errors };
}

/**
 * Full build. Writes src/{story,engine,modules} (generated) and build/{dev,release}.
 * @returns build info object
 */
export async function build(root, { modes = ['dev', 'release'] } = {}) {
  const project = loadProject(root);
  const { paths, config } = project;

  // 1. Scripts
  const { files, results, errors } = compileScripts(project);
  const vm = await collectVariablesAndModules(project);
  errors.push(...vm.errors);
  const start = resolveStart(project, results);
  if (!start) errors.push({ file: 'forge.yaml', line: 0, message: 'No start passage: set `start:` in forge.yaml or write a script' });
  if (errors.length) throw new BuildError(errors);

  const buildId = `b${timestampId()}`;
  const genStory = path.join(paths.src, 'story');
  const genEngine = path.join(paths.src, 'engine');
  const genModules = path.join(paths.src, 'modules');
  for (const d of [genStory, genEngine, genModules]) rmrf(d);

  // 2. Story twee (one file per script, with editor positions laid out per file)
  const deps = loadDeps(root);
  results.forEach((r, fileIdx) => {
    r.passages.forEach((p, i) => { p.position = `${i * 140 + 40},${fileIdx * 160 + 40}`; });
    const out = path.join(genStory, path.basename(r.ast.file).replace(/\.script\.md$/, '.twee'));
    writeText(out, toTwee(r.passages, GENERATED_TWEE));
    recordDeps(root, deps, rel(root, out), [r.ast.file]);
  });

  // 3. Engine passages
  const characters = {};
  project.characters.forEach((c, i) => { characters[c.id] = { name: c.name || c.id, color: c.ui?.color || PALETTE[i % PALETTE.length] }; });
  const endings = results.flatMap((r) => r.refs.endings).map((e) => ({ id: e.id, title: e.title, passage: e.passage }));
  const title = config.title || 'Untitled';
  const ifid = config.ifid;
  const formatVersion = config.format?.version || null;

  vm.vars.set('forge_media', { init: {}, source: 'media runtime' });
  const storyInit = [...vm.vars.entries()].map(([n, v]) => `<<set $${n} to ${JSON.stringify(v.init ?? null)}>>`).join('\n');

  // Media: approved assets from assets/manifest.yaml, and which referenced cues still lack one.
  const media = collectMedia(root, results);
  writeText(path.join(genEngine, 'story.twee'), [
    GENERATED_TWEE,
    '',
    `:: StoryTitle\n${title}\n`,
    `:: StoryData\n${JSON.stringify({ ifid, format: 'SugarCube', 'format-version': formatVersion, start, zoom: 1 }, null, 2)}\n`,
    `:: StoryInit [nobr]\n${storyInit || '/% no variables declared %/'}\n`,
  ].join('\n'));
  // Images each passage shows, so the runtime can prefetch them when a link to that passage appears.
  const mediaByPassage = {};
  for (const m of results.flatMap((r) => r.refs.media)) {
    if (m.kind !== 'bg' && m.kind !== 'portrait') continue;
    const k = `${m.kind}:${m.kind === 'portrait' ? `${m.args[0]}.${m.args[1] || 'neutral'}` : m.args[0]}`;
    if (!media.urls[k]) continue;
    (mediaByPassage[m.passage] ||= []).includes(k) || mediaByPassage[m.passage].push(k);
  }
  const dataCtx = {
    characters,
    modules: vm.modules,
    invariants: vm.invariants,
    endings,
    assets: media.urls,
    assetsSmall: {},
    posters: {},
    mediaByPassage,
    build: { id: buildId, ifid, title, historyMaxStates: config.runtime?.history_max_states || 20 },
  };
  const data = (mode) => forgeDataJs(dataCtx, mode);
  const engineDir = path.join(PLUGIN_ROOT, 'engine');
  writeText(path.join(genEngine, 'forge-data.twee'), wrapCode('forge-data.js', ['script'], data('dev')));
  writeText(path.join(genEngine, 'core.twee'), [
    wrapCode('forge-core.js', ['script'], readText(path.join(engineDir, 'core.js'))),
    wrapCode('forge-media.js', ['script'], readText(path.join(engineDir, 'media.js'))),
    wrapCode('forge-core.css', ['stylesheet'], readText(path.join(engineDir, 'core.css'))),
    readText(path.join(engineDir, 'widgets.twee')),
  ].join('\n'));
  writeText(path.join(genEngine, 'debug.twee'), [
    wrapCode('forge-debug.js', ['script', 'debug'], readText(path.join(engineDir, 'debug.js'))),
    wrapCode('forge-debug.css', ['stylesheet', 'debug'], readText(path.join(engineDir, 'debug.css'))),
  ].join('\n'));

  // 4. Loop modules
  // JS runs once per instance; CSS and widgets are shared per module type.
  const typesDone = new Set();
  for (const m of vm.moduleFiles) {
    const type = path.basename(m.dir);
    const parts = [];
    const read = (f) => (fs.existsSync(path.join(m.dir, f)) ? readText(path.join(m.dir, f)).replace(/__MODULE_ID__/g, m.id) : null);
    const js = read('module.js');
    if (js) parts.push(wrapCode(`module-${m.id}.js`, ['script'], js));
    if (!typesDone.has(type)) {
      typesDone.add(type);
      const css = read('module.css');
      if (css) parts.push(wrapCode(`module-${type}.css`, ['stylesheet'], css));
      const widgets = read('widgets.twee');
      if (widgets) parts.push(widgets);
    }
    writeText(path.join(genModules, `${m.id}.twee`), parts.join('\n'));
  }

  // 5. Gather passages in load order: engine, modules, story, custom
  const order = [
    path.join(genEngine, 'story.twee'),
    path.join(genEngine, 'forge-data.twee'),
    path.join(genEngine, 'core.twee'),
    ...listFiles(genModules, (f) => f.endsWith('.twee')),
    path.join(genEngine, 'debug.twee'),
    ...listFiles(genStory, (f) => f.endsWith('.twee')),
    ...listFiles(path.join(paths.src, 'custom'), (f) => f.endsWith('.twee')),
  ];
  for (const f of listFiles(path.join(paths.src, 'custom'), (f) => /\.(js|css)$/.test(f))) {
    const gen = path.join(genEngine, `custom-${path.basename(f)}.twee`);
    writeText(gen, wrapCode(`custom/${path.basename(f)}`, [f.endsWith('.js') ? 'script' : 'stylesheet'], readText(f)));
    order.push(gen);
  }
  const all = order.flatMap((f) => parseTwee(readText(f), rel(root, f)));
  const dup = all.map((p) => p.name).filter((n, i, a) => a.indexOf(n) !== i);
  if (dup.length) throw new BuildError(dup.map((n) => ({ file: 'src', line: 0, message: `Duplicate passage name '${n}'` })));

  // 6. HTML
  if (!fs.existsSync(paths.formatJs)) throw new Error('SugarCube format not installed (vendor/sugarcube-2/format.js). Run: node .forge/forge.mjs setup');
  const format = loadStoryFormat(readText(paths.formatJs));
  const outputs = {};
  for (const mode of modes) {
    const passages = all
      .filter((p) => mode === 'dev' || !p.tags.includes('debug'))
      .map((p) => (p.name === 'forge-data.js' ? { ...p, text: data(mode) } : p));
    const html = compileHtml({ passages, format, title, ifid, start });
    const out = path.join(paths.build, mode, 'index.html');
    writeText(out, html);
    rmrf(path.join(paths.build, mode, 'media'));
    let mediaBytes = 0;
    for (const [k, rel] of Object.entries(media.files)) {
      const dest = path.join(paths.build, mode, media.urls[k]);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.copyFileSync(path.join(root, rel), dest);
      mediaBytes += fs.statSync(dest).size;
    }
    writeText(path.join(paths.build, mode, 'story.twee'), toTwee(passages.map((p) => ({ ...p, position: p.meta?.position }))));
    outputs[mode] = { html: rel(root, out), bytes: Buffer.byteLength(html), passages: passages.length, mediaFiles: Object.keys(media.files).length, mediaBytes };
  }

  // 7. Manifest + info
  const manifest = {
    buildId,
    start,
    lines: results.flatMap((r) => r.refs.lines),
    links: results.flatMap((r) => r.refs.links),
    media: results.flatMap((r) => r.refs.media),
    endings: results.flatMap((r) => r.refs.endings),
    variables: Object.fromEntries([...vm.vars.entries()].map(([n, v]) => [n, v])),
    invariants: vm.invariants,
  };
  writeJson(path.join(paths.build, 'script-manifest.json'), manifest);
  writeJson(path.join(paths.build, 'forge-data.json'), dataCtx);
  const info = {
    id: buildId,
    at: new Date().toISOString(),
    title,
    start,
    format: { name: format.name, version: format.version },
    scripts: files.map((f) => rel(root, f)),
    storyPassages: results.reduce((n, r) => n + r.passages.length, 0),
    endings: endings.map((e) => e.id),
    media: { referenced: media.referenced.length, available: Object.keys(media.files).length, missing: media.missing },
    outputs,
  };
  writeJson(path.join(paths.build, 'build-info.json'), info);
  saveDeps(root, deps);
  return info;
}
